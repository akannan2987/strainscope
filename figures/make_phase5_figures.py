def ring_layout(linked: pd.DataFrame):
    """Each community as a ring of dots, the rings side by side. A ring keeps
    every label readable, even in a community where everything is linked."""
    pos, centre_of = {}, {}
    groups = list(linked.groupby("community"))
    x = 0.0
    for c, grp in groups:
        r = 0.35 + 0.075 * len(grp)
        x += r
        centre_of[c] = (x, 0.0)
        ids = grp.sort_values(["node_type", "label"])["node_id"].tolist()
        for i, nid in enumerate(ids):
            ang = np.pi / 2 - 2 * np.pi * i / len(ids)
            pos[nid] = (x + r * np.cos(ang), r * np.sin(ang))
        x += r + 1.0
    ring_layout.centres = centre_of
    return pos


