ARSENAL_ORDER = ["Bacteria", "Cross-kingdom", "Fungi", "Oomycete", "Yeast",
                 "Plant-growth (other trait)", "Accessory noise"]


def mechanism_rows(nodes: pd.DataFrame, edges: pd.DataFrame):
    """Rows for the map: each gene with a mechanism (or a data-only link),
    with the compound it makes on the same row."""
    n = nodes.set_index("node_id")
    acts = edges[edges["relation"] == "acts_by"]
    makes = edges[edges["relation"] == "makes"].set_index("from_id")["to_id"].to_dict()
    stats = edges[(edges["relation"] == "associated_with")]
    genes = sorted(set(acts.loc[acts["from_id"].str.startswith("gene:"), "from_id"])
                   | {g for g in stats["from_id"] if g.startswith("gene:") and g not in set(acts["from_id"])})
    mode_of = acts.groupby("from_id")["to_id"].agg(list).to_dict()

    def order(g):
        a = n.loc[g, "arsenal"] if "arsenal" in n.columns else ""
        m = mode_of.get(g, ["zz"])[0]
        return (ARSENAL_ORDER.index(a) if a in ARSENAL_ORDER else 99, m, g)
    rows = []
    for g in sorted(genes, key=order):
        rows.append({"gene": g, "compound": makes.get(g), "modes": mode_of.get(g, []),
                     "compound_modes": mode_of.get(makes.get(g), []),
                     "arsenal": n.loc[g, "arsenal"], "data_only": g not in mode_of})
    return rows


def draw_mechanism_map():
    nodes, edges = _read("nodes.csv"), _read("edges.csv")
    if nodes is None:
        print("  (no graph yet; run `python src/strainscope/graph.py all` first)")
        return
    n = nodes.set_index("node_id")
    rows = mechanism_rows(nodes, edges)
    gap = 0.42
    y_of = {r["gene"]: -i * gap for i, r in enumerate(rows)}
    modes = sorted({m for r in rows for m in r["modes"] + r["compound_modes"]})
    mode_y = {m: np.mean([y_of[r["gene"]] for r in rows if m in r["modes"] + r["compound_modes"]])
              for m in modes}
    # spread the modes evenly in the order of their average row, so labels never overlap
    ordered = sorted(modes, key=lambda m: -mode_y[m])
    span = np.linspace(0, -gap * (len(rows) - 1), len(ordered)) if len(ordered) > 1 else [0]
    mode_y = dict(zip(ordered, span))
    outcome_ids = sorted(edges.loc[edges["relation"] == "contributes_to", "to_id"].unique())
    out_y = {o: np.mean([mode_y[m] for m in modes
                         if ((edges["from_id"] == m) & (edges["to_id"] == o)).any()] or [0]) for o in outcome_ids}
    fig, ax = plt.subplots(figsize=(13, 0.42 * len(rows) + 2.2))
    X_GENE, X_COMP, X_MODE, X_OUT = 0.0, 2.3, 5.3, 8.7
    for r in rows:
        y = y_of[r["gene"]]
        colour = ARSENAL_COLOURS.get(r["arsenal"], GREY)
        box(ax, X_GENE, y - 0.16, 1.5, 0.32, tint(colour), colour, n.loc[r["gene"], "label"], fs=7.5,
            dashed=r["data_only"])
        if r["compound"]:
            box(ax, X_COMP, y - 0.16, 1.9, 0.32, tint(GOLD, 0.85), GOLD, n.loc[r["compound"], "label"], fs=7.5)
            ax.plot([X_GENE + 1.5, X_COMP], [y, y], color=GOLD, lw=1.2)
        for m in r["modes"]:
            if r["compound"] and m in r["compound_modes"]:
                continue                     # the compound's line already shows this mode
            ax.plot([X_GENE + 1.5, X_MODE], [y, mode_y[m]], color=colour, lw=0.8, alpha=0.55)
        if r["compound"]:
            for m in r["compound_modes"]:
                ax.plot([X_COMP + 1.9, X_MODE], [y, mode_y[m]], color=colour, lw=0.8, alpha=0.55)
        if r["data_only"]:
            target = "outcome:disease suppression"
            ax.plot([X_GENE + 1.5, X_OUT], [y, out_y.get(target, 0)], color=RED, lw=1.2, ls="--")
            ax.text(X_COMP + 0.1, y - 0.05, "statistics only, no known mechanism", fontsize=7.5,
                    color=RED, va="center", style="italic")
    for m in modes:
        box(ax, X_MODE, mode_y[m] - 0.2, 2.5, 0.4, tint(TYPE_COLOURS["ModeOfAction"]),
            TYPE_COLOURS["ModeOfAction"], n.loc[m, "label"], fs=7.8)
        for o in outcome_ids:
            if ((edges["from_id"] == m) & (edges["to_id"] == o)).any():
                ax.plot([X_MODE + 2.5, X_OUT], [mode_y[m], out_y[o]], color=TYPE_COLOURS["Outcome"], lw=1.6)
    for o in outcome_ids:
        box(ax, X_OUT, out_y[o] - 0.3, 2.1, 0.6, tint(TYPE_COLOURS["Outcome"]), TYPE_COLOURS["Outcome"],
            n.loc[o, "label"], fs=8.5, bold=True)
    top = 0.6
    for x, label in ((X_GENE, "gene"), (X_COMP, "compound it makes"), (X_MODE, "mode of action"),
                     (X_OUT, "outcome")):
        ax.text(x, top, label, fontsize=9, color=SOFT, fontweight="bold")
    ax.set_xlim(-0.2, 11.0); ax.set_ylim(-gap * len(rows) - 0.2, top + 0.4); ax.axis("off")
    handles = [plt.Line2D([], [], marker="s", ls="", markersize=9, markerfacecolor=tint(c), markeredgecolor=c,
                          label=a) for a, c in ARSENAL_COLOURS.items() if a in {r["arsenal"] for r in rows}]
    ax.legend(handles=handles, loc="lower left", fontsize=7.5, frameon=False, ncol=4,
              bbox_to_anchor=(0.0, -0.06))
    ax.set_title("The mechanism map: how each weapon reaches an outcome (colour = whose weapon)",
                 fontsize=11.5, color=INK)
    footnote(fig, "StrainScope: SIMULATED data · links from the domain model in src/strainscope/ontology.py")
    save(fig, "mechanism_map.png")


