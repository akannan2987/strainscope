ONTOLOGY_LAYOUT = {"ReferenceStrain": (0.2, 7.4), "Kingdom": (0.2, 5.6), "Genus": (3.4, 5.6),
                   "Strain": (6.6, 5.6), "Gene": (4.4, 3.3), "Compound": (8.8, 3.3),
                   "Pathway": (12.3, 5.6), "ChemicalClass": (12.3, 1.0),
                   "ModeOfAction": (6.6, 1.0), "Outcome": (6.6, -1.2)}
BOX_W, BOX_H = 2.4, 1.0


def draw_ontology():
    fig, ax = plt.subplots(figsize=(13.5, 7.6))
    ax.set_xlim(-0.2, 15.0); ax.set_ylim(-1.8, 8.6); ax.axis("off")
    centre = {t: (x + BOX_W / 2, y + BOX_H / 2) for t, (x, y) in ONTOLOGY_LAYOUT.items()}

    def anchor(a, b):
        """Where an arrow from box a towards box b leaves a's edge."""
        (xa, ya), (xb, yb) = centre[a], centre[b]
        dx, dy = xb - xa, yb - ya
        sx = (BOX_W / 2) / abs(dx) if dx else np.inf
        sy = (BOX_H / 2) / abs(dy) if dy else np.inf
        s = min(sx, sy)
        return xa + dx * s, ya + dy * s

    drawn = set()
    for rel, (froms, tos, _) in RELATIONS.items():
        for f in froms:
            for t in tos:
                if f not in centre or t not in centre:
                    continue
                stats = rel == "associated_with"
                colour = RED if stats else SOFT
                if f == t:                                             # subclass_of: a loop
                    x, y = centre[f]
                    ax.add_patch(FancyArrowPatch((x + 0.5, y + BOX_H / 2), (x + 1.0, y + BOX_H / 2),
                                                 arrowstyle="-|>", mutation_scale=11, color=colour,
                                                 connectionstyle="arc3,rad=-2.2", lw=1.3))
                    ax.text(x + 0.8, y + 1.25, rel, fontsize=7.5, color=colour, ha="center")
                    continue
                rad = {("Gene", "Outcome"): 0.35, ("Compound", "Outcome"): -0.35}.get((f, t), 0.0)
                (x1, y1), (x2, y2) = anchor(f, t), anchor(t, f)
                arrow(ax, x1, y1, x2, y2, colour=colour, lw=1.3, ls="--" if stats else "-", rad=rad)
                key = (rel, t)
                if key in drawn and rel in ("acts_by", "associated_with", "belongs_to"):
                    continue                                           # one label per relation and target
                drawn.add(key)
                mx, my = (x1 + x2) / 2, (y1 + y2) / 2
                if rad:
                    mx += -1.15 if rad > 0 else 1.15
                ax.text(mx, my, rel, fontsize=7.5, color=colour, ha="center", va="center",
                        bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none"))
    for t, (x, y) in ONTOLOGY_LAYOUT.items():
        info = NODE_TYPES[t]
        real = info["origin"] == "real"
        box(ax, x, y, BOX_W, BOX_H, tint(info["colour"]), info["colour"], dashed=real)
        ax.text(x + BOX_W / 2, y + 0.64, t, ha="center", fontsize=9.5, fontweight="bold", color=INK)
        ax.text(x + BOX_W / 2, y + 0.28, f"e.g. {info['example'][:30]}", ha="center", fontsize=7.2,
                color=SOFT, style="italic")
    ax.text(0.2, -1.55, "solid arrow = a fact or a mechanism    red dashed arrow = statistics only "
            "(Phases 3 and 4)    dashed box = appears when the real tables of Phases 1b and 1c are present",
            fontsize=8, color=SOFT)
    ax.set_title("The domain model (ontology): what can be connected to what", fontsize=12, color=INK)
    footnote(fig, "StrainScope: drawn from src/strainscope/ontology.py")
    save(fig, "ontology_map.png")


