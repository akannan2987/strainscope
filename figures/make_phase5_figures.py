def footnote(fig, text="StrainScope: SIMULATED data"):
    # placed just BELOW the figure, so it never collides with an axis label
    fig.text(0.99, -0.01, text, ha="right", va="top", fontsize=7, color=GREY, style="italic")


def save(fig, name):
    fig.savefig(FIG / name, bbox_inches="tight")
    plt.close(fig)
    print(f"  drew figures/{name}")


def box(ax, x, y, w, h, fill, edge, text="", fs=9, bold=False, colour=INK, dashed=False):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.08",
                                facecolor=fill, edgecolor=edge, lw=1.4,
                                linestyle="--" if dashed else "-"))
    if text:
        ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs,
                color=colour, fontweight="bold" if bold else "normal")


def arrow(ax, x1, y1, x2, y2, colour=SOFT, lw=1.5, ls="-", rad=0.0):
    ax.add_patch(FancyArrowPatch((x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=12,
                                 color=colour, lw=lw, linestyle=ls,
                                 connectionstyle=f"arc3,rad={rad}"))


def tint(hex_colour, amount=0.82):
    """A pale version of a colour, for box fills."""
    rgb = np.array([int(hex_colour[i:i + 2], 16) for i in (1, 3, 5)]) / 255
    return tuple(rgb + (1 - rgb) * amount)


def _read(name: str) -> pd.DataFrame | None:
    path = GRAPH_DIR / name
    return pd.read_csv(path) if path.exists() else None


