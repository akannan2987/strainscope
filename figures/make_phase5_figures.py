def _wrap(text, width=20):
    """Break a long label onto two lines at a space."""
    text = text.replace(" and ", " + ")
    if len(text) <= width or " " not in text:
        return text
    cut = text.rfind(" ", 0, width + 1)
    cut = cut if cut > 0 else text.find(" ")
    return text[:cut] + "\n" + text[cut + 1:]


def _draw_one(ax, strain_row, rows):
    ax.set_xlim(0, 10); ax.axis("off")
    mech = rows[rows["kind"] == "mechanism"]
    flags = rows[rows["kind"] == "data only"]
    missing = rows[rows["kind"] == "missing"]
    items = len(mech) + len(flags) + len(missing)
    ax.set_ylim(-items * 1.0 + 0.3, 0.8)
    sy = -(items - 1) * 0.5
    label = f"{strain_row['strain_id']}\nrank {int(strain_row['rank'])}" if pd.notna(strain_row["rank"]) \
        else strain_row["strain_id"]
    box(ax, 0.0, sy - 0.45, 1.8, 0.9, tint(GREY), GREY, label, fs=8, bold=True)
    box(ax, 8.2, sy - 0.45, 1.8, 0.9, tint(GREEN), GREEN, "disease\nsuppression", fs=8, bold=True)
    y = 0.0
    for r in mech.itertuples(index=False):
        gene = r.feature or "(gene call missing)"
        box(ax, 2.2, y - 0.3, 1.4, 0.6, tint(BLUE), BLUE, gene, fs=7.5)
        arrow(ax, 1.8, sy, 2.2, y, colour=GREY, lw=1)
        x_next = 3.6
        if isinstance(r.compound, str) and r.compound:
            box(ax, 3.9, y - 0.3, 1.5, 0.6, tint(GOLD, 0.85), GOLD, r.compound, fs=7.5)
            arrow(ax, 3.6, y, 3.9, y, colour=GOLD, lw=1)
            x_next = 5.4
        box(ax, 5.7, y - 0.3, 2.2, 0.6, tint(PURPLE), PURPLE, _wrap(r.mode), fs=6.8)
        arrow(ax, x_next, y, 5.7, y, colour=PURPLE, lw=1)
        arrow(ax, 7.9, y, 8.2, sy, colour=GREEN, lw=1.4)
        y -= 1.0
    for r in flags.itertuples(index=False):
        box(ax, 2.2, y - 0.3, 1.4, 0.6, "white", RED, r.feature, fs=7.5, dashed=True)
        arrow(ax, 1.8, sy, 2.2, y, colour=GREY, lw=1)
        arrow(ax, 3.6, y, 8.2, sy, colour=RED, lw=1, ls="--")
        ax.text(4.0, y - 0.05, "? statistics only", fontsize=7.5, color=RED, va="center")
        y -= 1.0
    for r in missing.itertuples(index=False):
        box(ax, 2.2, y - 0.3, 1.4, 0.6, "white", GREY, f"no {r.feature}", fs=7.5, dashed=True)
        ax.text(3.8, y, r.text.replace("lacks ", "lacks: "), fontsize=7.2, color=SOFT, va="center")
        y -= 1.0
    p = strain_row["probability"]
    ax.set_title(f"{strain_row['strain_id']}: predicted {p:.0%}" if pd.notna(p) else strain_row["strain_id"],
                 fontsize=10, color=INK)


