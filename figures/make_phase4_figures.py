def draw_calibration_curve():
    curve, summary = _read("calibration_curve.csv"), _read("calibration_summary.csv")
    if curve is None or summary is None:
        return
    s = summary.set_index("version")
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.8), gridspec_kw={"width_ratios": [1.2, 1]})
    ax = axes[0]
    ax.plot([0, 1], [0, 1], color=GREY, ls="--", lw=1.2, label="perfect calibration")
    for version, colour, label in (("raw", RED, "raw (rare class up-weighted)"),
                                   ("calibrated", GREEN, "calibrated (Platt scaling)")):
        d = curve[(curve["version"] == version) & (curve["n"] > 0)]
        ax.plot(d["mean_predicted"], d["observed_rate"], color=colour, lw=2, marker="o",
                label=f"{label}: error {s.loc[version, 'ece_pooled']:.3f}")
        ax.scatter(d["mean_predicted"], d["observed_rate"], s=np.sqrt(d["n"]) * 3, color=colour,
                   alpha=0.25)
    ax.set_xlabel("what the model said (average predicted probability in the bin)")
    ax.set_ylabel("what happened (share truly effective)")
    ax.set_title("Reliability diagram: 6,000 out-of-fold predictions", fontsize=10.5, color=INK)
    ax.legend(fontsize=8.5, loc="upper left")
    ax = axes[1]
    names = ["truly effective", "raw model says", "calibrated says"]
    vals = [s.loc["raw", "observed_rate_mean"], s.loc["raw", "mean_predicted_mean"],
            s.loc["calibrated", "mean_predicted_mean"]]
    ax.bar(names, vals, color=[GREY, RED, GREEN], alpha=0.85)
    for i, v in enumerate(vals):
        ax.text(i, v + 0.008, f"{v:.1%}", ha="center", fontsize=10, fontweight="bold")
    ax.set_ylim(0, max(vals) * 1.25)
    ax.set_ylabel("average across test strains")
    ax.set_title("On average: how many strains are effective?", fontsize=10.5, color=INK)
    footnote(fig, "StrainScope: SIMULATED data · dot size = number of predictions in the bin")
    save(fig, "calibration_curve.png")


def draw_importance():
    imp = _read("feature_importance.csv")
    board = _read("scoreboard.csv")
    if imp is None or board is None:
        return
    winner = board.loc[board["is_winner"], "model_key"].iloc[0]
    other = [k for k in imp["model_key"].unique() if k != winner][0]
    w = imp[imp["model_key"] == winner].head(22).iloc[::-1]
    o = imp[imp["model_key"] == other].set_index("feature")["importance_mean"]
    fig, ax = plt.subplots(figsize=(10.5, 7.6))
    colours = [KINGDOM_COLOURS.get(a, GREY) if r != "decoy" else DECOY_COLOUR
               for r, a in zip(w["role"], w["arsenal"])]
    y = np.arange(len(w))
    ax.barh(y, w["importance_mean"], xerr=w["importance_sd"], color=colours, alpha=0.9, capsize=2)
    ax.scatter([o.get(f, np.nan) for f in w["feature"]], y, marker="o", facecolor="white",
               edgecolor=INK, s=30, zorder=3, label=f"{other.replace('_', ' ')} (second opinion)")
    for yi, (_, r) in zip(y, w.iterrows()):
        mark = "✓" if r["reliably_important"] else "·"
        ax.text(-0.004, yi, mark, ha="right", va="center", fontsize=10,
                color=GREEN if r["reliably_important"] else GREY)
    ax.set_yticks(y)
    ax.set_yticklabels([f"{f}  ({'decoy' if r == 'decoy' else a})"
                        for f, r, a in zip(w["feature"], w["role"], w["arsenal"])], fontsize=8.5)
    ax.set_xlabel("drop in AUC when the feature is shuffled in unseen strains (bigger = more relied on)")
    ax.set_title(f"What the {winner.replace('_', ' ')} relies on (colour = whose weapon, grey = "
                 "decoy, ✓ = reliably important)", fontsize=10.5, color=INK)
    ax.legend(fontsize=8.5, loc="lower right")
    ax.set_xlim(-0.012, max(w["importance_mean"].max(), o.max()) * 1.15)
    footnote(fig, "StrainScope: SIMULATED data · the kingdom label matters because every "
                  "feature is measured against its kingdom's average")
    save(fig, "feature_importance.png")


def draw_errors():
    oof, board = _read("oof_predictions.csv"), _read("scoreboard.csv")
    errors = _read("error_by_group.csv")
    if oof is None or errors is None or board is None:
        return
    winner = board.loc[board["is_winner"], "model_key"].iloc[0]
    # The error analysis judges the winner exactly as the scoreboard does: its
    # out-of-fold probability (rare class up-weighted) against the 50 % line.
    prob = oof[f"p_{winner}"]
    wrong = oof[f"correct_share_{winner}"] < 0.5
    fig, axes = plt.subplots(1, 2, figsize=(12.5, 4.9), gridspec_kw={"width_ratios": [1.5, 1]})
    ax = axes[0]
    ax.scatter(oof.loc[~wrong, "suppression_score"], prob[~wrong], s=12,
               color=GREY, alpha=0.45, label="right (most repeats)")
    ax.scatter(oof.loc[wrong, "suppression_score"], prob[wrong], s=26,
               color=RED, alpha=0.85, label="wrong (most repeats)")
    ax.axvline(CUTOFF, color=INK, lw=1.2)
    ax.axhline(0.5, color=GOLD, lw=1, ls="--")
    ax.axvspan(CUTOFF - 5, CUTOFF + 5, color=GOLD, alpha=0.12)
    ax.text(CUTOFF + 0.5, 1.03, "65 % = the line that defines \"effective\"", fontsize=8.5,
            color=INK)
    ax.text(ax.get_xlim()[0] + 1, 0.52, "flag line (50 %)", fontsize=8, color=GOLD)
    ax.set_xlabel("measured disease suppression (%)")
    ax.set_ylabel("the winner's probability (out-of-fold)")
    ax.set_title("Each dot is a strain. The mistakes crowd around the 65 % line.",
                 fontsize=10.5, color=INK)
    ax.legend(fontsize=8.5, loc="upper left")
    ax = axes[1]
    d = errors[errors["group_type"].str.startswith("distance")]
    ax.bar(range(len(d)), d["error_rate"], color=[RED, RED, GOLD, GREEN], alpha=0.85)
    for i, (_, r) in enumerate(d.iterrows()):
        ax.text(i, r["error_rate"] + 0.01, f"{r['error_rate']:.0%}\n({r['n_errors']}/{r['n_strains']})",
                ha="center", fontsize=8.5)
    ax.set_xticks(range(len(d)))
    ax.set_xticklabels([g.replace(" points", "\npoints") for g in d["group"]], fontsize=8.5)
    ax.set_ylabel("share of strains the model gets wrong")
    ax.set_ylim(0, d["error_rate"].max() * 1.3)
    ax.set_title("Error rate by distance from the 65 % line", fontsize=10.5, color=INK)
    footnote(fig, "StrainScope: SIMULATED data · near the line, the label itself is partly "
                  "measurement noise")
    save(fig, "errors_near_cutoff.png")


def draw_top_n():
    pred = _read("predictions.csv")
    if pred is None:
        return
    pred = pred.sort_values("rank")
    found = pred["is_effective"].cumsum().to_numpy()
    n = np.arange(1, len(pred) + 1)
    base = pred["is_effective"].mean()
    total = int(pred["is_effective"].sum())
    fig, ax = plt.subplots(figsize=(9.5, 4.8))
    ax.plot(n, found, color=GREEN, lw=2.4, label="test strains in the model's order")
    ax.plot(n, n * base, color=GREY, lw=1.6, ls="--", label="test strains in random order")
    ax.plot(n, np.minimum(n, total), color=INK, lw=1, ls=":", label="a perfect oracle")
    for mark in (50, 100, 150):
        ax.scatter([mark], [found[mark - 1]], color=GREEN, zorder=3)
        ax.annotate(f"top {mark}: {found[mark - 1]} winners\n(random: {mark * base:.0f})",
                    (mark, found[mark - 1]), textcoords="offset points", xytext=(10, -28),
                    fontsize=8.5, color=INK)
    ax.set_xlim(0, 300)
    ax.set_ylim(0, total * 1.08)
    ax.set_xlabel("number of strains sent for expensive testing, best-ranked first")
    ax.set_ylabel("truly effective strains found")
    ax.set_title("What a screening team gets: test the top of the ranking, find the winners early",
                 fontsize=10.5, color=INK)
    ax.legend(fontsize=8.5, loc="lower right")
    footnote(fig, "StrainScope: SIMULATED data · ranking uses out-of-fold probabilities "
                  "(no strain ranked by a model that saw it)")
    save(fig, "top_n_ranking.png")


