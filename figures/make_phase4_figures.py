def draw_imbalance():
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 5.2))
    rng = np.random.default_rng(3)
    effective = np.zeros(100, dtype=bool)
    effective[rng.choice(100, 24, replace=False)] = True
    catches = effective & (rng.random(100) < 0.87)               # a good model finds most ...
    false_alarms = (~effective) & (rng.random(100) < 0.12)       # ... with a few false alarms

    def verdict(flagged):
        # the scores are COMPUTED from the dots drawn, never typed in
        accuracy = np.mean(flagged == effective)
        ber = (np.mean(~flagged[effective]) + np.mean(flagged[~effective])) / 2
        return f"accuracy {accuracy:.0%}  ·  balanced error {ber:.2f}" + \
            ("  (a coin)" if abs(ber - 0.5) < 1e-9 else "")

    lazy, useful = np.zeros(100, dtype=bool), catches | false_alarms
    panels = [("The lazy model: \"no strain is effective\"", lazy, verdict(lazy)),
              ("A useful model: flags most winners, a few false alarms", useful, verdict(useful))]
    for ax, (title, flagged, verdict) in zip(axes, panels):
        ax.set_xlim(-0.6, 9.6)
        ax.set_ylim(-1.9, 9.8)
        ax.set_aspect("equal")
        ax.axis("off")
        for i in range(100):
            x, y = i % 10, 9 - i // 10
            face = GREEN if effective[i] else "#E3E7ED"
            ax.add_patch(Circle((x, y), 0.36, facecolor=face, edgecolor="white", lw=1))
            if flagged[i]:
                ax.add_patch(Circle((x, y), 0.46, facecolor="none", edgecolor=INK, lw=1.6))
        ax.set_title(title, fontsize=11, color=INK)
        ax.text(4.5, -1.2, verdict, ha="center", fontsize=10.5, fontweight="bold",
                color=RED if not flagged.any() else GREEN)
    fig.suptitle("100 strains, 24 truly effective (green). A black ring = \"the model says "
                 "effective\".", fontsize=12, color=INK, y=1.0)
    footnote(fig, "StrainScope: illustration; the 24 % share matches the simulated library")
    save(fig, "imbalance_pictograph.png")


