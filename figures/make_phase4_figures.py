def draw_calibration_idea():
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.6), gridspec_kw={"width_ratios": [1.15, 1]})
    ax = axes[0]
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 6)
    ax.set_aspect("equal")
    ax.axis("off")
    ax.set_title("A forecaster says \"30 % chance of rain\" on 10 days …", fontsize=11, color=INK)
    for row, (label, rainy, colour) in enumerate([("well calibrated: it rains on 3", 3, GREEN),
                                                  ("over-confident: it rains on 1", 1, RED)]):
        y = 4.2 - row * 2.6
        for d in range(10):
            ax.add_patch(Circle((0.6 + d * 0.95, y), 0.36,
                                facecolor=BLUE if d < rainy else "#F1D58A",
                                edgecolor="white", lw=1))
            ax.text(0.6 + d * 0.95, y, "R" if d < rainy else "S", ha="center", va="center",
                    fontsize=8, color="white", fontweight="bold")
        ax.text(5, y - 0.85, label, ha="center", fontsize=10, color=colour, fontweight="bold")
    ax.text(5, 0.1, "R = rainy day, S = sunny day", ha="center", fontsize=8.5, color=SOFT)
    ax = axes[1]
    p = np.linspace(0, 1, 11)
    ax.plot([0, 1], [0, 1], color=GREY, ls="--", lw=1.2, label="perfect: says 30 %, happens 30 %")
    ax.plot(p, p ** 1.8, color=RED, lw=2, marker="o", ms=4, label="says too much (over-predicts)")
    ax.plot(p, np.clip(p * 1.0 + 0.02 * np.sin(p * 9), 0, 1), color=GREEN, lw=2, marker="o",
            ms=4, label="calibrated")
    ax.set_xlabel("what the model says (predicted probability)")
    ax.set_ylabel("what really happened (observed share)")
    ax.set_title("The reliability diagram", fontsize=11, color=INK)
    ax.legend(fontsize=8.5, loc="upper left")
    fig.suptitle("Calibration: when a model says \"30 %\", it should come true about 3 times in 10",
                 fontsize=12, color=INK, y=1.02)
    footnote(fig, "StrainScope: illustration")
    save(fig, "calibration_explained.png")


