# RESULT — genes × metabolites correlation heatmap
# =============================================================================
def draw_heatmap():
    path = ART / "cross_block_correlation.csv"
    if not path.exists():
        print("  (no correlations — run `twin`)")
        return
    c = pd.read_csv(path)
    ann = pd.read_csv(ART / "feature_annotations.csv").set_index("feature")
    mat = c.pivot(index="gene", columns="metabolite", values="spearman_rho")
    # order rows/cols by arsenal so each kingdom's weapons sit together
    order_key = {k: i for i, k in enumerate(["Bacteria", "Fungi", "Yeast", "Oomycete",
                                             "Cross-kingdom", "Plant-growth (other trait)",
                                             "Accessory noise", "Background chemistry"])}
    rows = sorted(mat.index, key=lambda f: (order_key.get(ann.loc[f, "arsenal"], 99), f))
    cols = sorted(mat.columns, key=lambda f: (order_key.get(ann.loc[f, "arsenal"], 99), f))
    mat = mat.loc[rows, cols]
    fig, ax = plt.subplots(figsize=(10, 9))
    im = ax.imshow(mat.to_numpy(), cmap="RdBu_r", vmin=-1, vmax=1, aspect="auto")
    ax.set_xticks(range(len(cols))); ax.set_xticklabels(cols, rotation=60, ha="right", fontsize=8)
    ax.set_yticks(range(len(rows))); ax.set_yticklabels(rows, fontsize=8)
    ax.grid(False)
    pairs = c[c["is_producer_pair"]]
    for _, r in pairs.iterrows():
        ax.add_patch(Rectangle((cols.index(r["metabolite"]) - 0.5, rows.index(r["gene"]) - 0.5),
                               1, 1, fill=False, edgecolor=INK, lw=1.4))
    fig.colorbar(im, ax=ax, shrink=0.6, label="Spearman correlation (centred data)")
    ax.set_title("Genes × chemistry: each gene lights up with its OWN product (outlined squares)",
                 fontsize=10.5)
    footnote(fig)
    save(fig, "cross_block_heatmap.png")


