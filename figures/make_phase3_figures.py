# RESULT — why we compare like with like (centring within kingdom)
# =============================================================================
def draw_like_with_like():
    raw = BLOCKS / "block_genomics.csv"
    if not raw.exists():
        print("  (no prepared blocks yet — run `python src/strainscope/integrate.py prepare`)")
        return
    ann = pd.read_csv(ART / "feature_annotations.csv")
    signal_genes = ann.loc[(ann["block"] == "genomics") & (ann["role"] == "signal"), "feature"]
    o = pd.read_csv(BLOCKS / "outcome.csv", index_col=0)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.6), sharey=False)
    for ax, fname, title in [(axes[0], "block_genomics.csv", "AS MEASURED: weapons counted on one scale"),
                             (axes[1], "block_genomics_centred.csv",
                              "CENTRED WITHIN KINGDOM: “more weapons than its peers?”")]:
        g = pd.read_csv(BLOCKS / fname, index_col=0)
        score = g[[c for c in signal_genes if c in g.columns]].sum(axis=1)
        rng = np.random.default_rng(7)
        for i, k in enumerate(["Bacteria", "Fungi", "Yeast", "Oomycete"]):
            sel = o["kingdom"] == k
            x = i + rng.uniform(-0.3, 0.3, sel.sum())
            eff = o.loc[sel, "is_effective"].to_numpy() == 1
            ax.scatter(x[~eff], score[sel].to_numpy()[~eff], s=12, color=DECOY_COLOUR, alpha=0.9,
                       label="not effective" if i == 0 else None)
            ax.scatter(x[eff], score[sel].to_numpy()[eff], s=16, color=GREEN, alpha=0.95,
                       label="effective" if i == 0 else None, edgecolor="white", lw=0.3)
        ax.set_xticks(range(4)); ax.set_xticklabels(["Bacteria", "Fungi", "Yeast", "Oomycete"])
        ax.set_ylabel("signal-gene count" if "centred" not in fname else "count minus kingdom average")
        ax.set_title(title, fontsize=10.5)
        if "centred" in fname:
            ax.axhline(0, color=SOFT, lw=1, ls="--")
    axes[0].legend(loc="upper right", fontsize=8, frameon=False)
    axes[0].annotate("an effective yeast\ncarries fewer weapons than\nmany ineffective bacteria",
                     xy=(2, 1.5), xytext=(2.35, 5.5), fontsize=8, color=INK,
                     arrowprops=dict(arrowstyle="->", color=SOFT))
    fig.suptitle("The efficacy score judges each strain against its own kingdom — so the features must too",
                 fontsize=11.5, color=INK, y=1.02)
    footnote(fig)
    save(fig, "compare_like_with_like.png")


