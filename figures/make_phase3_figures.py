def draw_sample_map():
    path = ART / "diablo_sample_scores.csv"
    if not path.exists():
        print("  (no DIABLO results — skipping diablo_sample_map.png)")
        return
    s = pd.read_csv(path)
    avg = s.groupby(["strain_id", "kingdom", "is_effective"], as_index=False)[["comp1", "comp2"]].mean()
    markers = {"Bacteria": "o", "Fungi": "s", "Yeast": "^", "Oomycete": "D"}
    fig, ax = plt.subplots(figsize=(8.5, 6))
    for k, mk in markers.items():
        for eff, colour, lab in [(0, DECOY_COLOUR, "not effective"), (1, GREEN, "effective")]:
            d = avg[(avg["kingdom"] == k) & (avg["is_effective"] == eff)]
            ax.scatter(d["comp1"], d["comp2"], marker=mk, s=26, color=colour,
                       edgecolor=SOFT if eff == 0 else "white", lw=0.4, alpha=0.9,
                       label=f"{k} · {lab}")
    ax.axvline(0, color=SOFT, lw=0.8, ls="--")
