             "margin-top:36px}p{color:#5f6b7a;line-height:1.5}.note{font-size:13px;font-style:italic}"
             "</style></head><body>",
             "<h1>StrainScope · Phase 3 — integration explorer</h1>",
             "<p class='note'>Simulated data, disclosed as such. Built by "
