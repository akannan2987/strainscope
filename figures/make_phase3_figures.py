def draw_agreement():
    sig_path, sel_path = ART / "diablo_signature.csv", ART / "python_selection.csv"
    if not (sig_path.exists() and sel_path.exists()):
        print("  (need both DIABLO and twin results — skipping two_languages_agreement.png)")
        return
    sig = pd.read_csv(sig_path)
    c1 = sig[(sig["component"] == 1) & (sig["stability"] >= 0.8)]
    r_set = set(c1["feature"])
    sel = pd.read_csv(sel_path)
    py_set = set(sel.loc[sel["selection_frequency"] >= 0.8, "feature"])
    both, r_only, py_only = sorted(r_set & py_set), sorted(r_set - py_set), sorted(py_set - r_set)
    fig, ax = plt.subplots(figsize=(11, 5.4))
    ax.set_xlim(0, 11); ax.set_ylim(0, 5.6); ax.axis("off"); ax.set_aspect("equal")
    ax.add_patch(Circle((4.1, 2.7), 2.5, facecolor=PURPLE, alpha=0.16, edgecolor=PURPLE, lw=1.5))
    ax.add_patch(Circle((6.9, 2.7), 2.5, facecolor=BLUE, alpha=0.16, edgecolor=BLUE, lw=1.5))
    ax.text(2.6, 5.35, f"DIABLO (R) — robust: {len(r_set)}", color=PURPLE, fontsize=10, ha="center")
    ax.text(8.4, 5.35, f"lasso (Python) — robust: {len(py_set)}", color=BLUE, fontsize=10, ha="center")

    def column(items, x, y_top, colour, step=0.235, limit=19):
        for i, f in enumerate(items[:limit]):
            ax.text(x, y_top - i * step, f, ha="center", fontsize=7.4, color=colour)
        if len(items) > limit:
            ax.text(x, y_top - limit * step, f"+{len(items) - limit} more", ha="center",
                    fontsize=7.4, color=SOFT)
    column(r_only, 2.65, 4.6, PURPLE)
    column(both, 5.5, 4.85, INK)
    if py_only:
        column(py_only, 8.35, 4.6, BLUE)
    else:
        ax.text(8.35, 2.8, "nothing here:\nevery lasso pick is\nalso a DIABLO pick", ha="center",
                fontsize=8.5, color=BLUE, style="italic")
    ax.text(5.5, 0.05, f"{len(both)} in both · {len(r_only)} DIABLO-only · {len(py_only)} Python-only. "
            "The lasso keeps ONE of each correlated gene–product pair; DIABLO keeps both.",
            ha="center", fontsize=9, color=SOFT, style="italic")
    footnote(fig)
    save(fig, "two_languages_agreement.png")


