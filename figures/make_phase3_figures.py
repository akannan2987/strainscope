def draw_three_ways():
    fig, axes = plt.subplots(1, 3, figsize=(13, 4.6))
    titles = ["EARLY integration\n“glue the tables side by side”",
              "INTERMEDIATE integration (DIABLO)\n“find what the tables agree on”",
              "LATE integration\n“ask each table, then vote”"]
    for ax, title in zip(axes, titles):
        ax.set_xlim(0, 4); ax.set_ylim(0, 4.2); ax.axis("off")
        ax.set_title(title, fontsize=10.5, color=INK)

    # Early: two blocks -> one wide table -> one model
    a = axes[0]
    mini_table(a, 0.2, 2.7, 5, 4, BLUE); mini_table(a, 0.2, 1.3, 5, 4, GOLD)
    a.text(0.42, 3.42, "genes", fontsize=8, color=SOFT); a.text(0.3, 2.0, "chemistry", fontsize=8, color=SOFT)
    arrow(a, 0.8, 2.6, 1.55, 2.2)
    mini_table(a, 1.6, 1.85, 4, 4, BLUE, 0.1); mini_table(a, 2.0, 1.85, 4, 4, GOLD, 0.1)
    a.text(2.0, 1.6, "one wide table", ha="center", fontsize=8, color=SOFT)
    arrow(a, 2.45, 2.05, 3.0, 2.05)
    box(a, 3.0, 1.75, 0.9, 0.6, "#EAECEF", GREY, "model", 9, True)
    a.text(2.0, 0.55, "simple · but the bigger table\ncan drown out the smaller one", ha="center",
           fontsize=8.5, color=INK)

    # Intermediate: each block -> its own score; scores must agree + predict Y
    b = axes[1]
    mini_table(b, 0.15, 2.7, 5, 4, BLUE); mini_table(b, 0.15, 0.9, 5, 4, GOLD)
    box(b, 1.35, 2.75, 1.05, 0.5, "#E8F0FE", BLUE, "gene score", 8.5)
    box(b, 1.35, 0.95, 1.05, 0.5, "#FFF3CD", GOLD, "chem score", 8.5)
    arrow(b, 0.75, 3.0, 1.33, 3.0); arrow(b, 0.75, 1.2, 1.33, 1.2)
    arrow(b, 1.87, 2.73, 1.87, 1.47, PURPLE, 1.8, "<|-|>", "--")
    b.text(1.95, 2.1, "agree", fontsize=8, color=PURPLE)
    box(b, 2.95, 1.85, 0.9, 0.55, "#E6F4EA", GREEN, "effective?", 8.5, True)
    arrow(b, 2.42, 3.0, 3.1, 2.42, GREEN); arrow(b, 2.42, 1.2, 3.1, 1.85, GREEN)
    b.text(2.0, 0.25, "each table keeps its voice · a FEW features\nper table form the signature", ha="center",
           fontsize=8.5, color=INK)

    # Late: each block -> its own model -> combine predictions
    c = axes[2]
    mini_table(c, 0.15, 2.7, 5, 4, BLUE); mini_table(c, 0.15, 0.9, 5, 4, GOLD)
    box(c, 1.3, 2.75, 0.9, 0.5, "#EAECEF", GREY, "model A", 8.5)
    box(c, 1.3, 0.95, 0.9, 0.5, "#EAECEF", GREY, "model B", 8.5)
    arrow(c, 0.75, 3.0, 1.28, 3.0); arrow(c, 0.75, 1.2, 1.28, 1.2)
    box(c, 2.75, 1.85, 1.1, 0.55, "#F3E8FD", PURPLE, "average\nthe votes", 8.5)
    arrow(c, 2.22, 3.0, 2.85, 2.42); arrow(c, 2.22, 1.2, 2.85, 1.85)
    c.text(2.0, 0.25, "robust · but cannot see\npatterns that span both tables", ha="center",
           fontsize=8.5, color=INK)
    fig.suptitle("Three ways to combine two kinds of measurement on the same strains",
                 fontsize=12, color=INK, y=1.02)
    footnote(fig, "StrainScope — concept illustration")
    save(fig, "integration_three_ways.png")


