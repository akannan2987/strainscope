"""
figures/make_phase3_figures.py — the teaching figures for Phase 3 (multi-omics integration).
============================================================================================
Two kinds of picture, both regenerated by this one script:

  CONCEPTS (drawn, no data needed) — what integration IS:
    figures/integration_three_ways.png      early · intermediate (DIABLO) · late
    figures/diablo_idea.png                 three "witnesses" that must agree
    figures/cross_validation_explained.png  how a score is earned honestly

  RESULTS (read from artifacts/integration/ — never invented):
    figures/compare_like_with_like.png      why we centre within kingdom
    figures/diablo_error_by_component.png   error vs number of components
    figures/diablo_signature.png            the component-1 signature, graded
    figures/integration_scoreboard.png      every approach on one honest scale
    figures/cross_block_heatmap.png         genes × metabolites correlations
    figures/diablo_sample_map.png           600 strains on the DIABLO map
    figures/two_languages_agreement.png     R and Python, compared

  INTERACTIVE (one page, opens in any browser, works offline):
    docs/interactive/integration_explorer.html
    docs/interactive/plotly.min.js          the charting library, shared by explorer pages

Run (from the project root, venv active) AFTER the integration steps:
    python figures/make_phase3_figures.py

If R/DIABLO has not run (the Python-only path), the DIABLO figures are skipped
with a note and everything else is still drawn.
"""
