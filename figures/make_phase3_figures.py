def _diablo_summary() -> dict:
    path = ART / "diablo_summary.csv"
    if not path.exists():
        return {}
    s = pd.read_csv(path)
    return dict(zip(s["key"], s["value"]))


def _scoreboard() -> pd.DataFrame:
    board = pd.read_csv(ART / "python_scoreboard.csv")
    board["language"] = "Python"
    summ = _diablo_summary()
    if summ:
        board = pd.concat([board, pd.DataFrame([{
            "approach": f"Intermediate integration (DIABLO, R, {summ['ncomp_fitted']} components)",
            "ber_mean": float(summ["cv_ber_final"]), "ber_sd": float(summ["cv_ber_final_sd"]),
            "auc_mean": np.nan, "auc_sd": np.nan, "language": "R"}])], ignore_index=True)
    return board


def draw_scoreboard():
    if not (ART / "python_scoreboard.csv").exists():
        print("  (no scoreboard — run `python src/strainscope/integrate.py twin`)")
        return
    b = _scoreboard().sort_values("ber_mean", ascending=False)
    fig, ax = plt.subplots(figsize=(10, 5.2))
    colours = []
    for name, lang in zip(b["approach"], b["language"]):
        if name.startswith("Control"):
            colours.append(DECOY_COLOUR)
        elif lang == "R":
            colours.append(PURPLE)
        elif "only" in name:
            colours.append(BLUE)
        else:
            colours.append(GREEN)
    ax.barh(b["approach"], b["ber_mean"], xerr=b["ber_sd"], color=colours, capsize=3,
            edgecolor="white")
    for y, (v, sd) in enumerate(zip(b["ber_mean"], b["ber_sd"])):
        ax.text(v + sd + 0.008, y, f"{v:.3f}", va="center", fontsize=8.5)
    ax.axvline(0.5, color=RED, ls=":", lw=1)
    ax.text(0.5, len(b) - 0.4, " coin toss", color=RED, fontsize=8)
    ax.set_xlim(0, 0.58)
    ax.set_xlabel("balanced error rate, cross-validated (lower is better)")
    ax.tick_params(axis="y", labelsize=8.5)
    ax.set_title("Integration beats either block alone; the controls behave like coins — as they must",
                 fontsize=10.5)
    footnote(fig, "StrainScope — SIMULATED data · grey = controls · blue = one block · "
                  "green = Python integration · purple = DIABLO")
    save(fig, "integration_scoreboard.png")


