def footnote(fig, text="StrainScope — SIMULATED data"):
    fig.text(0.99, 0.01, text, ha="right", va="bottom", fontsize=7, color=GREY,
             style="italic")


def save(fig, name):
    fig.savefig(FIG / name, bbox_inches="tight")
    plt.close(fig)
    print(f"  drew figures/{name}")


def box(ax, x, y, w, h, fill, edge, text="", fs=9, bold=False, colour=INK, dashed=False):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.08",
                                facecolor=fill, edgecolor=edge, lw=1.3,
                                linestyle="--" if dashed else "-"))
    if text:
        ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs,
                color=colour, fontweight="bold" if bold else "normal")


def arrow(ax, x1, y1, x2, y2, colour=SOFT, lw=1.6, style="-|>", ls="-"):
    ax.add_patch(FancyArrowPatch((x1, y1), (x2, y2), arrowstyle=style, mutation_scale=13,
                                 color=colour, lw=lw, linestyle=ls))


def mini_table(ax, x, y, rows, cols, colour, cell=0.11):
    """A little grid of squares — the pictograph for 'a block of data'."""
    for r in range(rows):
        for c in range(cols):
            ax.add_patch(Rectangle((x + c * cell, y + r * cell), cell * 0.88, cell * 0.88,
                                   facecolor=colour, edgecolor="white", lw=0.4,
                                   alpha=0.35 + 0.65 * ((r * 7 + c * 3) % 5) / 5))


