def _signature_table():
    sig = pd.read_csv(ART / "diablo_signature.csv")
    ann = pd.read_csv(ART / "feature_annotations.csv")
    return sig.merge(ann[["feature", "role", "arsenal", "description"]], on="feature", how="left")


def draw_signature():
    if not (ART / "diablo_signature.csv").exists():
        print("  (no DIABLO results — skipping diablo_signature.png)")
        return
    sig = _signature_table()
    c1 = sig[sig["component"] == 1]
    fig, axes = plt.subplots(1, 2, figsize=(12.5, 6.2))
    for ax, block, title in [(axes[0], "genomics", "Genes"), (axes[1], "metabolomics", "Chemistry")]:
        d = c1[c1["block"] == block].sort_values("loading", key=np.abs)
        colours = [DECOY_COLOUR if r != "signal" else KINGDOM_COLOURS.get(a, GREY)
                   for r, a in zip(d["role"], d["arsenal"])]
        ax.barh(d["feature"], d["loading"].abs(), color=colours, edgecolor="white")
        for y, (val, stab, role) in enumerate(zip(d["loading"].abs(), d["stability"], d["role"])):
            mark = "✓" if stab >= 0.8 else "✗"
            ax.text(val + 0.006, y, f"{mark} {stab:.0%}", va="center", fontsize=7.5,
                    color=GREEN if stab >= 0.8 else RED)
        ax.set_title(f"{title}: component-1 weights", fontsize=10.5)
        ax.set_xlabel("|weight| (how much the feature counts)")
        ax.set_xlim(0, max(0.55, d["loading"].abs().max() + 0.12))
        ax.tick_params(axis="y", labelsize=8.5)
    handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in KINGDOM_COLOURS.values()]
    handles.append(plt.Rectangle((0, 0), 1, 1, color=DECOY_COLOUR))
    labels = [f"{k} weapon" for k in KINGDOM_COLOURS] + ["decoy (no link to efficacy)"]
    fig.legend(handles, labels, loc="lower center", ncol=6, frameon=False, fontsize=8.5,
               bbox_to_anchor=(0.5, -0.03))
    fig.suptitle("The DIABLO signature: every kingdom's weapons on ONE axis. "
                 "✓/✗ = picked in ≥ 80 % of re-fits", fontsize=11.5, color=INK)
    footnote(fig)
    save(fig, "diablo_signature.png")


