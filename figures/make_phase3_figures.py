# CONCEPT 3 — cross-validation: earning a score honestly
# =============================================================================
def draw_cross_validation():
    fig, ax = plt.subplots(figsize=(11, 4.6))
    ax.set_xlim(0, 11); ax.set_ylim(0, 6.2); ax.axis("off")
    ax.text(5.5, 5.85, "5-fold cross-validation: every strain is tested exactly once, by a model that never saw it",
            ha="center", fontsize=11.5, color=INK)
    for fold in range(5):
        y = 4.7 - fold * 0.95
        ax.text(0.15, y + 0.28, f"round {fold + 1}", fontsize=9, color=INK)
        for part in range(5):
            test = part == fold
            ax.add_patch(Rectangle((1.3 + part * 1.45, y), 1.35, 0.6,
                                   facecolor=RED if test else "#E8F0FE",
                                   edgecolor=RED if test else BLUE, lw=1.2,
                                   alpha=0.85 if test else 1))
            ax.text(1.3 + part * 1.45 + 0.675, y + 0.3, "TEST" if test else "train",
                    ha="center", va="center", fontsize=8.5,
                    color="white" if test else BLUE, fontweight="bold" if test else "normal")
        ax.text(8.75, y + 0.3, f"→ score {fold + 1}", fontsize=9, color=SOFT, va="center")
    ax.text(9.9, 2.75, "average\nof 5\nscores", ha="center", fontsize=9, color=INK)
    arrow(ax, 9.75, 4.8, 9.85, 3.4, SOFT); arrow(ax, 9.75, 0.9, 9.85, 2.1, SOFT)
    ax.text(5.5, 0.12, "…then the whole thing is reshuffled and repeated 10 times. "
            "The ± we report is how much the average moves between reshuffles.",
            ha="center", fontsize=9, color=SOFT, style="italic")
    footnote(fig, "StrainScope — concept illustration")
    save(fig, "cross_validation_explained.png")


